#!/usr/bin/env node

const fs = require("fs")
const path = require("path")

const REPO_ROOT = path.resolve(__dirname, "../..")
const DEFAULT_MODELS_JSON = path.resolve(
  REPO_ROOT,
  "../codex/codex-rs/models-manager/models.json"
)
const OUTPUT_PATH = path.join(
  REPO_ROOT,
  "apps/protocol-bridge/src/llm/openai/codex-model-instructions.generated.ts"
)
const SUPPLEMENTAL_MODELS_JSON = path.join(
  __dirname,
  "supplemental-models.json"
)

function readArg(name) {
  const index = process.argv.indexOf(name)
  if (index === -1 || index + 1 >= process.argv.length) {
    return undefined
  }
  return process.argv[index + 1]
}

function resolveInputPath() {
  return path.resolve(
    readArg("--models-json") ||
      process.env.CODEX_MODELS_JSON ||
      DEFAULT_MODELS_JSON
  )
}

function assertFile(filePath, label) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`${label} does not exist: ${filePath}`)
  }
}

function loadCatalog(modelsJsonPath) {
  const raw = fs.readFileSync(modelsJsonPath, "utf8")
  const parsed = JSON.parse(raw)
  if (!Array.isArray(parsed.models)) {
    throw new Error(`Expected .models array in ${modelsJsonPath}`)
  }

  const catalog = {}
  for (const model of parsed.models) {
    const slug = typeof model.slug === "string" ? model.slug.trim() : ""
    const baseInstructions =
      typeof model.base_instructions === "string" ? model.base_instructions : ""
    const modelMessages =
      model.model_messages && typeof model.model_messages === "object"
        ? model.model_messages
        : undefined

    if (!slug || (!baseInstructions && !modelMessages)) {
      continue
    }

    catalog[slug] = {
      baseInstructions,
      profile: Object.fromEntries(
        Object.entries(model).filter(
          ([key]) => key !== "base_instructions" && key !== "model_messages"
        )
      ),
      modelMessages: modelMessages
        ? {
            runtime: Object.fromEntries(
              Object.entries(modelMessages).filter(
                ([key]) =>
                  key !== "instructions_template" &&
                  key !== "instructions_variables"
              )
            ),
            instructionsTemplate:
              typeof modelMessages.instructions_template === "string"
                ? modelMessages.instructions_template
                : undefined,
            instructionsVariables: modelMessages.instructions_variables
              ? {
                  personalityDefault:
                    typeof modelMessages.instructions_variables
                      .personality_default === "string"
                      ? modelMessages.instructions_variables.personality_default
                      : undefined,
                  personalityFriendly:
                    typeof modelMessages.instructions_variables
                      .personality_friendly === "string"
                      ? modelMessages.instructions_variables
                          .personality_friendly
                      : undefined,
                  personalityPragmatic:
                    typeof modelMessages.instructions_variables
                      .personality_pragmatic === "string"
                      ? modelMessages.instructions_variables
                          .personality_pragmatic
                      : undefined,
                }
              : undefined,
          }
        : undefined,
      includeSkillsUsageInstructions:
        model.include_skills_usage_instructions === true,
    }
  }

  return catalog
}

function buildOutput({
  modelsJsonPath,
  supplementalModelsPath,
  promptPath,
  fallbackBaseInstructions,
  catalog,
}) {
  const source = {
    modelsJson: path.relative(REPO_ROOT, modelsJsonPath),
    promptMd: path.relative(REPO_ROOT, promptPath),
  }

  return `// Generated by scripts/codex/sync-codex-model-instructions.js.
// Source: ${source.modelsJson}
${supplementalModelsPath ? `// Supplemental source: ${path.relative(REPO_ROOT, supplementalModelsPath)}\n` : ""}\
// Fallback source: ${source.promptMd}

export interface GeneratedCodexModelInstructionsVariables {
  personalityDefault?: string
  personalityFriendly?: string
  personalityPragmatic?: string
}

export interface GeneratedCodexModelMessages {
  runtime?: Readonly<Record<string, unknown>>
  instructionsTemplate?: string
  instructionsVariables?: GeneratedCodexModelInstructionsVariables
}

export interface GeneratedCodexModelInstructionEntry {
  profile?: Readonly<Record<string, unknown>>
  baseInstructions: string
  modelMessages?: GeneratedCodexModelMessages
  includeSkillsUsageInstructions?: boolean
}

export const CODEX_FALLBACK_BASE_INSTRUCTIONS = ${JSON.stringify(
    fallbackBaseInstructions
  )}

export const CODEX_MODEL_INSTRUCTION_CATALOG = ${JSON.stringify(
    catalog,
    null,
    2
  )} as const satisfies Record<string, GeneratedCodexModelInstructionEntry>
`
}

async function main() {
  const modelsJsonPath = resolveInputPath()
  assertFile(modelsJsonPath, "Codex models.json")

  const promptPath = path.join(path.dirname(modelsJsonPath), "prompt.md")
  assertFile(promptPath, "Codex fallback prompt.md")

  const outputPath = path.resolve(readArg("--out") || OUTPUT_PATH)
  const fallbackBaseInstructions = fs.readFileSync(promptPath, "utf8")
  const catalog = loadCatalog(modelsJsonPath)
  // Account-advertised models may ship ahead of the checked-out upstream
  // models.json. Keep their recorded profiles without replacing newer
  // upstream entries or deleting the existing model catalog.
  const supplementalModelsPath = process.argv.includes("--no-supplemental")
    ? undefined
    : path.resolve(
        readArg("--supplemental-models-json") || SUPPLEMENTAL_MODELS_JSON
      )
  if (supplementalModelsPath) {
    assertFile(supplementalModelsPath, "Supplemental Codex models.json")
    const supplemental = loadCatalog(supplementalModelsPath)
    for (const [slug, entry] of Object.entries(supplemental)) {
      if (!Object.hasOwn(catalog, slug)) catalog[slug] = entry
    }
  }
  const rawOutput = buildOutput({
    modelsJsonPath,
    supplementalModelsPath,
    promptPath,
    fallbackBaseInstructions,
    catalog,
  })

  const prettier = await import("prettier")
  const output = await prettier.format(rawOutput, {
    ...(await prettier.resolveConfig(OUTPUT_PATH)),
    parser: "typescript",
  })
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(outputPath) ||
      fs.readFileSync(outputPath, "utf8") !== output
    ) {
      throw new Error(
        "Generated Codex catalog is out of date; run codex:instructions:sync"
      )
    }
    process.stdout.write(
      `Verified ${Object.keys(catalog).length} Codex model profiles and instructions\n`
    )
    return
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  fs.writeFileSync(outputPath, output)
  process.stdout.write(
    `Synced ${Object.keys(catalog).length} Codex model instruction entries to ${path.relative(
      REPO_ROOT,
      outputPath
    )}\n`
  )
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`)
  process.exitCode = 1
})
